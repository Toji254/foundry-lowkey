import importlib.util
import pathlib
from unittest.mock import patch
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
MODULE = ROOT / "lowkey" / "lk.py"

spec = importlib.util.spec_from_file_location("lowkeycast_state_diff", MODULE)
lk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lk)


class StateDiffGeneratorTests(unittest.TestCase):
    def test_repeat_count_log_uses_explicit_uint256_type(self):
        captured = {}

        def capture_generated_test(_prefix, body, announce=False):
            captured["body"] = body
            return "test/Lowkey_state_diff_regression.t.sol"

        config = {
            "target": "0x" + "1" * 40,
            "actor": "Alice",
            "wallets": {},
            "rpc": "http://127.0.0.1:0",
        }

        with patch.object(
            lk,
            "encode_target_call",
            return_value=("ping()", "deadbeef"),
        ), patch.object(
            lk,
            "resolve_lab_value",
            return_value="0",
        ), patch.object(
            lk,
            "validate_solidity_value",
            return_value="0",
        ), patch.object(
            lk,
            "actor_address",
            return_value="0x" + "2" * 40,
        ), patch.object(
            lk,
            "write_generated_test",
            side_effect=capture_generated_test,
        ), patch.object(
            lk,
            "run_foundry",
            return_value=lk.CommandResult("compile failed", 1),
        ), patch.object(
            lk,
            "discard_generated_test",
        ):
            result = lk.run_state_diff(config, ["ping", "--repeat", "2"])

        self.assertEqual(result, 1)
        self.assertIn(
            'console2.log("REPEAT_COUNT", uint256(2));',
            captured["body"],
        )
        self.assertNotIn(
            'console2.log("REPEAT_COUNT", 2);',
            captured["body"],
        )
        self.assertIn(
            "target has no runtime code",
            captured["body"],
        )
        self.assertIn('vm.envExists("LOWKEY_RPC_URL")', captured["body"])
        self.assertIn('vm.envString("LOWKEY_RPC_URL")', captured["body"])
        self.assertIn("vm.createSelectFork(rpcUrl)", captured["body"])

    def test_lk_test_blocks_legacy_state_diff_without_code_guard(self):
        from pathlib import Path
        from tempfile import TemporaryDirectory
        from unittest.mock import patch

        with TemporaryDirectory() as tmp:
            root = Path(tmp)
            test_dir = root / "test"
            test_dir.mkdir()
            (test_dir / "Lowkey_state_diff_legacy.t.sol").write_text(
                "\n".join([
                    "// Generated by LowkeyCast. Records storage writes.",
                    "contract LowkeyStateDiff is Test {",
                    '    (bool success, bytes memory data) = TARGET.call(hex"deadbeef");',
                    "}",
                    "",
                ]),
                encoding="utf-8",
            )

            with patch.object(lk, "detected_project_root", return_value=str(root)):
                with patch.object(
                    lk,
                    "detect_project",
                    return_value={"backend": "foundry", "stacks": ["foundry"]},
                ):
                    with patch.object(lk, "run_foundry", return_value=0) as run_foundry:
                        result = lk.run_native_project_command({}, "test", [])

            self.assertEqual(result, 2)
            run_foundry.assert_not_called()

